#!/usr/bin/env python3
"""Generate the network-topology background SVG for index.html.

The background scrolls with the page. It is built from seven right-angle cable
runs laid out in a 1280x820 tile, scaled down and mirrored so the cables stay
continuous from tile to tile:

  * below the hero: one 2x2 mirrored block, repeated as an SVG <pattern>
    (a few KB for any page height);
  * the hero: a mild fisheye lens (r' = r^0.86 inside r < 1 around the hero
    centre, unchanged outside, so the lens meets the flat tiles without a seam),
    drawn as real paths and cut out of the pattern with a mask;
  * packets: short dashes animated along a few cables (SMIL), one alert packet.

All colours come from CSS (--text, --edge), so nothing here is theme specific.

Usage (stdlib only):
  python3 scripts/make-network-bg.py                      # print the markup
  python3 scripts/make-network-bg.py --inject index.html  # replace it in place
"""
import math
import sys

# ---- approved layout (1280x820 tile) ----
W, H = 1280, 820
RUNS = {
    "a": [(0, 150), (430, 150), (430, 300), (900, 300), (900, 190), (1280, 190)],
    "b": [(0, 540), (260, 540), (260, 430), (650, 430), (650, 610), (1280, 610)],
    "c": [(190, 0), (190, 230), (520, 230), (520, 820)],
    "d": [(1050, 0), (1050, 370), (770, 370), (770, 820)],
    "e": [(0, 730), (350, 730), (350, 680), (1010, 680), (1010, 760), (1280, 760)],
    "f": [(1180, 820), (1180, 500), (1280, 500)],
    "g": [(650, 0), (650, 90), (1280, 90)],
}

# ---- tuning (chosen in the mockup) ----
K = 0.15              # tile scale: 1 tile = 192x123 CSS px
POWER = 0.86          # fisheye strength
CY = 410              # lens centre: page centre-x (0), 410px from the top
HD = math.hypot(640, 410)  # lens radius (half-diagonal of 1280x820)
STEP = 24             # sample spacing inside the lens, px
PAGE_MAX = 8000       # packets are placed down to this depth (extra ones are clipped)
PACKET_EVERY = 1100   # one packet roughly every this many px below the hero
SVG_W = 2560          # wide enough for any screen; centred and clipped by CSS

# (run, duration s, begin offset s) for the hero packets
PACKETS = [("a", 14, 0), ("b", 18, -6), ("c", 16, -11), ("e", 22, -3)]
LOWER_COLS = [-2, 1, -1, 2, 0]

START = "<!-- network background: generated by scripts/make-network-bg.py -->"
END = "<!-- /network background -->"


def rnd(v):
    return math.floor(v + 0.5)


def place(pts, i, j):
    """Tile (i, j) in page px, x=0 at the page centre. Odd tiles are mirrored."""
    out = []
    for x, y in pts:
        xx = W - x if i & 1 else x
        yy = H - y if j & 1 else y
        out.append(((i * W + xx - W / 2) * K, CY + (j * H + yy - H / 2) * K))
    return out


def warp(p):
    x, y = p
    dy = y - CY
    d = math.hypot(x, dy)
    r = d / HD
    if d == 0 or r >= 1:
        return p
    s = r ** POWER / r
    return (x * s, CY + dy * s)


def sample(pts):
    """Subdivide segments that pass through the lens; leave the rest straight."""
    out = [pts[0]]
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        l2 = (x1 - x0) ** 2 + (y1 - y0) ** 2
        t = max(0.0, min(1.0, ((0 - x0) * (x1 - x0) + (CY - y0) * (y1 - y0)) / l2)) if l2 else 0.0
        near = math.hypot(x0 + (x1 - x0) * t, y0 + (y1 - y0) * t - CY) < HD
        n = max(1, math.ceil(math.sqrt(l2) / STEP)) if near else 1
        out += [(x0 + (x1 - x0) * k / n, y0 + (y1 - y0) * k / n) for k in range(1, n + 1)]
    return out


def poly(pts):
    return "M" + " ".join(f"{rnd(x)},{rnd(y)}" for x, y in pts)


def rel(pts):
    """Absolute start, then whole-pixel relative steps (smaller markup)."""
    r = [(rnd(x), rnd(y)) for x, y in pts]
    lx, ly = r[0]
    steps = []
    for x, y in r[1:]:
        if (x, y) != (lx, ly):
            steps.append(f"{x - lx},{y - ly}")
            lx, ly = x, y
    return f"M{r[0][0]},{r[0][1]}l" + " ".join(steps)


def tile_rect(i, j):
    return ((i * W - W / 2) * K, CY + (j * H - H / 2) * K, W * K, H * K)


def anim(dur, begin):
    return (f'<animate attributeName="stroke-dashoffset" values="1000;0" dur="{dur}s" '
            f'begin="{begin}s" repeatCount="indefinite"/>')


def build():
    # 1) the repeating 2x2 mirrored block
    px, py, tw, th = tile_rect(0, 0)
    block = "".join(
        f'<path d="{poly([(x - px, y - py) for x, y in place(RUNS[n], i, j)])}"/>'
        for i in (0, 1) for j in (0, 1) for n in RUNS
    )

    # 2) hero tiles inside the lens: warped, merged into one path, cut out of the pattern
    hero, holes, carriers = [], [], []
    ni = math.ceil(HD / (W * K) + 0.5)
    nj = math.ceil(HD / (H * K) + 0.5)
    for i in range(-ni, ni + 1):
        for j in range(-nj, nj + 1):
            x, y, w, h = tile_rect(i, j)
            nx, ny = max(x, min(0, x + w)), max(y, min(CY, y + h))
            if math.hypot(nx, ny - CY) >= HD:
                continue
            holes.append(f'<rect x="{rnd(x)}" y="{rnd(y)}" width="{rnd(w)}" height="{rnd(h)}"/>')
            for n, run in RUNS.items():
                pts = [warp(p) for p in sample(place(run, i, j))]
                if i == 0 and j == 0 and n in "abcde":
                    carriers.append(f'<path id="net-{n}" pathLength="1000" d="{poly(pts)}"/>')
                hero.append(rel(pts))

    # 3) packets: four on the hero, one alert, then one every PACKET_EVERY px
    pk = [f'<use href="#net-{n}" class="pk">{anim(d, b)}</use>' for n, d, b in PACKETS]
    pk.append(
        '<use href="#net-d" class="pk alert" opacity="0">' + anim(12, 0)
        + '<animate attributeName="opacity" values="0;0;0.9;0.9;0;0" '
          'keyTimes="0;0.25;0.3;0.7;0.75;1" dur="36s" repeatCount="indefinite"/></use>'
    )
    b = 1
    while CY + b * PACKET_EVERY < PAGE_MAX:
        n, d, beg = PACKETS[b % 4]
        j, i = rnd(b * PACKET_EVERY / (H * K)), LOWER_COLS[b % len(LOWER_COLS)]
        pk.append(f'<path class="pk" pathLength="1000" d="{poly(place(RUNS[n], i, j))}">{anim(d, beg)}</path>')
        b += 1

    big = f'x="-{SVG_W // 2}" y="0" width="{SVG_W}" height="40000"'
    return "\n".join([
        START,
        '<div class="netwrap" aria-hidden="true"><svg id="net" focusable="false">',
        "<defs>" + "".join(carriers),
        f'<pattern id="net-tile" patternUnits="userSpaceOnUse" x="{rnd(px)}" y="{rnd(py)}" '
        f'width="{rnd(2 * tw)}" height="{rnd(2 * th)}"><g class="lines">{block}</g></pattern>',
        f'<mask id="net-hole" maskUnits="userSpaceOnUse" {big}><rect {big} fill="#fff"/>'
        f'<g fill="#000">{"".join(holes)}</g></mask>',
        "</defs>",
        f'<g transform="translate({SVG_W // 2} 0)"><rect {big} fill="url(#net-tile)" mask="url(#net-hole)"/>',
        f'<g class="lines"><path d="{" ".join(hero)}"/></g>',
        "<g>" + "".join(pk) + "</g></g>",
        "</svg></div>",
        END,
    ])


def main():
    markup = build()
    if len(sys.argv) == 3 and sys.argv[1] == "--inject":
        path = sys.argv[2]
        with open(path, encoding="utf-8") as f:
            page = f.read()
        if page.count(START) != 1 or page.count(END) != 1:
            sys.exit(f"{path}: expected exactly one pair of network-background markers")
        a, b = page.index(START), page.index(END)
        page = page[:a] + markup + page[b + len(END):]
        with open(path, "w", encoding="utf-8") as f:
            f.write(page)
        print(f"updated {path} ({len(markup)} bytes of background markup)")
    elif len(sys.argv) == 1:
        print(markup)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
